// Headless check of the Me screen: your own numbers replace the placeholders. Usage: node scripts/me.mjs
import { chromium, devices } from "playwright";
import { pathToFileURL } from "node:url";
import path from "node:path";
import assert from "node:assert/strict";
const b = await chromium.launch();
const p = await (await b.newContext({ ...devices["iPhone 13"], hasTouch: true })).newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const profile = () => p.evaluate(() => new Promise((res) => { const o = indexedDB.open("pocket-deck"); o.onsuccess = () => { const r = o.result.transaction("profile").objectStore("profile").get("me"); r.onsuccess = () => res(r.result); }; }));
await p.goto(pathToFileURL(path.resolve("dist-single/index.html")).href);
await p.waitForTimeout(900);
await p.getByRole("button", { name: "Skip for now" }).click();
await p.waitForTimeout(500);
await p.locator(".supper-opt", { hasText: "Fish" }).click();
await p.getByRole("button", { name: "Plan my day" }).click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Menu" }).click();
await p.waitForTimeout(500);
await p.getByRole("button", { name: "Me", exact: true }).click();
await p.waitForTimeout(500);
assert.ok(await p.locator(".me-note").isVisible(), "placeholder warning shows before setup");
await p.locator(".me-tile", { hasText: "About you" }).click();
await p.waitForTimeout(300);
const before = await p.locator(".me-targets dd").nth(1).textContent();
await p.locator(".krow", { hasText: "Cycle" }).click();
await p.locator(".krow", { hasText: "Swim" }).click();
await p.getByLabel("Weight").fill("95");
await p.getByLabel("Height").fill("182");
await p.getByLabel("Age").fill("38");
await p.getByRole("button", { name: "Use these numbers" }).click();
await p.waitForTimeout(500);
const saved = await profile();
assert.deepEqual([...saved.movements].sort(), ["cycle", "swim", "walk"], "movement is a multi-select");
assert.equal(saved.weightKg, 95); assert.equal(saved.heightCm, 182); assert.equal(saved.setUp, true);
console.log("sat limit:", before, "→", await p.locator(".me-targets dd").nth(1).textContent());
await p.getByRole("button", { name: "Back to Me" }).click();
await p.waitForTimeout(300);
assert.equal(await p.locator(".me-note").count(), 0, "warning gone once set up");

// Handedness is its own page and applies straight away: the menu glides to the other corner.
await p.locator(".me-tile", { hasText: "Menu and cards" }).click();
await p.waitForTimeout(300);
const xBefore = (await p.getByRole("button", { name: "Menu" }).boundingBox()).x;
await p.getByRole("button", { name: /Left-handed/ }).click();
await p.waitForTimeout(70);
const xMid = (await p.getByRole("button", { name: "Menu" }).boundingBox()).x;
await p.waitForTimeout(900);
const xEnd = (await p.getByRole("button", { name: "Menu" }).boundingBox()).x;
assert.ok(xBefore > 200 && xEnd < 100, "menu ends in the left corner");
assert.ok(xMid < xBefore - 10 && xMid > xEnd + 10, `menu glides between corners (x ${xBefore} → ${Math.round(xMid)} → ${xEnd})`);
console.log("glide:", Math.round(xBefore), "→", Math.round(xMid), "→", Math.round(xEnd));
assert.equal((await profile()).hand, "left");
await p.reload();
await p.waitForTimeout(900);
assert.equal((await profile()).weightKg, 95);
console.log("errors:", errors.length ? errors : "none");
assert.equal(errors.length, 0);
await b.close();
